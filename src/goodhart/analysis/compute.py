"""GPU time of the fetched runner jobs: the compute figure of the README and the write-up.

::

    python -m goodhart.analysis.compute [--runner-results results/fetched]

reads every ``<job>/summary.json`` of the fetched runner outputs, sums its ``seconds`` (the
job's wall time, counted as GPU time) and writes ``results/analysis/compute.json`` and
``compute.md``: the total, the number of jobs, the jobs that exited with a non-zero code, and
the totals by stage. Failed jobs count, since they used the GPU. The outputs name stages, never
a job or a path. The summaries do not record the GPU model.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from goodhart.analysis.common import RUNNER_RESULTS
from goodhart.io import read_json, write_json

OUT_FILE = "results/analysis/compute.json"


def analyze(runner_results: str | Path) -> dict[str, Any]:
    """Totals over every ``*/summary.json`` under ``runner_results``."""
    paths = sorted(Path(runner_results).glob("*/summary.json"))
    if not paths:
        raise FileNotFoundError(f"no */summary.json under {runner_results}")
    stages: dict[str, dict[str, Any]] = {}
    failed: list[dict[str, Any]] = []
    total = 0
    for path in paths:
        summary = read_json(path)
        if "seconds" not in summary:
            raise ValueError(f"{path.parent.name}/summary.json has no 'seconds'")
        stage, seconds, rc = str(summary.get("stage")), int(summary["seconds"]), summary.get("rc")
        entry = stages.setdefault(stage, {"jobs": 0, "seconds": 0})
        entry["jobs"] += 1
        entry["seconds"] += seconds
        total += seconds
        if rc != 0:
            failed.append({"stage": stage, "rc": rc, "seconds": seconds})
    for entry in stages.values():
        entry["hours"] = round(entry["seconds"] / 3600, 2)
    return {
        "jobs": len(paths),
        "seconds": total,
        "hours": round(total / 3600, 2),
        "failed": failed,
        "stages": dict(sorted(stages.items())),
    }


def render_markdown(payload: dict[str, Any]) -> str:
    """The report ``compute.md``."""
    failed = payload["failed"]
    failed_text = (
        "; ".join(f"{f['stage']} (exit code {f['rc']}, {f['seconds']} s)" for f in failed)
        if failed
        else "none"
    )
    lines = [
        "# GPU time of the runner jobs",
        "",
        "Generated by `python -m goodhart.analysis.compute` (`make compute`) from the "
        "`summary.json` of every job in the fetched runner outputs under `results/fetched`; "
        "`seconds` is a job's wall time, counted as GPU time. The summaries do not record the "
        "GPU model. Failed jobs are counted.",
        "",
        f"- Jobs: {payload['jobs']}",
        f"- Total: {payload['seconds']} s = {payload['hours']:.2f} GPU-hours",
        f"- Failed jobs, counted in the total: {failed_text}",
        "",
        "| Stage | Jobs | Seconds | GPU-hours |",
        "|---|---|---|---|",
    ]
    for stage, entry in payload["stages"].items():
        lines.append(f"| {stage} | {entry['jobs']} | {entry['seconds']} | {entry['hours']:.2f} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> dict[str, Any]:
    """CLI: writes ``--out`` and the markdown report next to it."""
    parser = argparse.ArgumentParser(description="GPU time of the fetched runner jobs")
    parser.add_argument("--runner-results", default=RUNNER_RESULTS)
    parser.add_argument("--out", default=OUT_FILE, help="JSON file to write")
    args = parser.parse_args(argv)
    payload = analyze(args.runner_results)
    out = Path(args.out)
    write_json(out, payload)
    report = out.with_suffix(".md")
    report.write_text(render_markdown(payload), encoding="utf-8")
    hours = f"{payload['hours']:.2f}"
    print(f"{payload['jobs']} jobs, {hours} GPU-hours; wrote {out.name}, {report.name}")
    return payload


if __name__ == "__main__":
    main()
